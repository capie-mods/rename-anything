StateTable = dict[int, list[int]]
"""State ID to its VP provinces (at most :data:`VP_SLOTS`), sorted by state ID."""


def slots_expr(prefix: str) -> str:
    """Return the localisation text that renders every slot of one buffer.

    Args:
        prefix: Buffer prefix such as ``B``, ``N``, ``J`` or ``VC<k>``.

    Returns:
        ``[ROOT.RN_<prefix>_0]`` through ``[ROOT.RN_<prefix>_31]`` concatenated.
    """
    return "".join(f"[ROOT.RN_{prefix}_{k}]" for k in range(MAXLEN))


def state_buckets(states: StateTable) -> list[int]:
    """Return the sorted state-ID buckets that hold at least one state.

    Args:
        states: State table.

    Returns:
        Bucket numbers ``state_id // STATE_BUCKET`` in ascending order.
    """
    return sorted({s // STATE_BUCKET for s in states})


def bucket_has_slot(states: StateTable, bucket: int, slot: int) -> bool:
    """Return whether any state of a bucket has a VP in the given slot.

    Args:
        states: State table.
        bucket: Bucket number.
        slot: VP slot index.

    Returns:
        True when the bucket needs a lookup table for that slot.
    """
    return any(s // STATE_BUCKET == bucket and len(v) > slot for s, v in states.items())
