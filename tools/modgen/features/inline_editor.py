"""In-place editor: copy ``tools/inline_editor/`` into the mod.

The in-place editor (country, leader and party editors, the party tabs, the
rename cooldown, the status line, the decision that opens the Characters tab
and a hidden placeholder for subjects) is hand-written source. This slice only
copies it: script and GUI files get a generated-file header and the cooldown
length, localisation goes to every language (Polish from the Polish source,
the rest from English).

It also writes ``rn_editor_bridge_available``, the gate of every in-place editor
window, because the hand-written triggers must not define it twice.
"""

from __future__ import annotations

from typing import NamedTuple

from modgen.common import INLINE_SRC, LANGS, POLISH
from modgen.features.cooldown import COOLDOWN_DAYS

COOLDOWN_TOKEN = "@RN_COOLDOWN_DAYS@"  # noqa: S105 - a template placeholder, not a secret
"""Placeholder in the source that is replaced by :data:`COOLDOWN_DAYS`."""

TOKEN_PREFIX = "@RN_"  # noqa: S105 - a template placeholder prefix, not a secret
"""Prefix of every placeholder; one left over after substitution is an error."""

LOCALISATION_DIR = "localisation/"
"""Relative folder of the source's localisation files."""


class InlineFile(NamedTuple):
    """One output file of the in-place editor copy."""

    relative: str
    """POSIX path relative to ``mod/``."""

    text: str
    """File contents."""

    bom: bool
    """Whether the file needs a UTF-8 byte order mark (localisation)."""


def gen_inline_editor() -> list[InlineFile]:
    """Return every in-place editor file copied from :data:`~modgen.common.INLINE_SRC`.

    Script and GUI files get a generated-file header and the ``@RN_COOLDOWN_DAYS@``
    token replaced by :data:`COOLDOWN_DAYS`. Localisation is written for every
    language in :data:`~modgen.common.LANGS`: ``polish`` from the Polish source and
    every other language from the English source with its own ``l_<lang>:``
    header, which is how the legacy UI strings treat the other languages too.

    Returns:
        One entry per output file, in a stable order.

    Raises:
        ValueError: A script or GUI file still contains an unknown ``@RN_`` token.
    """
    out: list[InlineFile] = []
    for src in sorted(p for p in INLINE_SRC.rglob("*") if p.is_file()):
        rel = src.relative_to(INLINE_SRC).as_posix()
        text = src.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
        if rel.startswith(LOCALISATION_DIR):
            lang_src = rel.split("/")[1]
            targets = [POLISH] if lang_src == POLISH else [x for x in LANGS if x != POLISH]
            for lang in targets:
                body = text.replace(f"l_{lang_src}:", f"l_{lang}:", 1)
                name = src.name.replace(f"_l_{lang_src}.yml", f"_l_{lang}.yml")
                out.append(InlineFile(f"{LOCALISATION_DIR}{lang}/{name}", body, bom=True))
            continue
        text = text.replace(COOLDOWN_TOKEN, str(COOLDOWN_DAYS))
        if TOKEN_PREFIX in text:
            msg = f"unresolved {TOKEN_PREFIX} token in tools/inline_editor/{rel}"
            raise ValueError(msg)
        header = f"# GENERATED by tools/gen.py from tools/inline_editor/{rel} - edit the source.\n"
        out.append(InlineFile(rel, header + text, bom=False))
    return out


def bridge_gate_trigger() -> str:
    """Return ``rn_editor_bridge_available``, the gate of every in-place editor window.

    It also gates the legacy country Apply. It is ``always = yes`` until the
    native editor bridge exposes a presence signal that triggers can read
    (``rn_native_cap`` is only a command temp and ``RN_PLUGIN_STATUS`` only a
    localisation override), so without the extension the pencils are still
    shown and Apply reports that the extension is missing.

    Returns:
        The trigger with its comment lines.
    """
    return """# In-place editor (country/leader/parties) is shown only when the native editor bridge is present.
# OPEN: there is no script-visible presence signal yet (rn_native_cap exists only as a command
# temp injected into the Apply command; RN_PLUGIN_STATUS is a localisation override). The Native
# agent will provide one; replace the body below with it (e.g. has_global_flag = <signal>).
rn_editor_bridge_available = {
	always = yes
}
"""  # noqa: E501 - generated script lines are emitted verbatim
