"""The two generated localisation files of every language.

* ``rename_anything_l_<lang>.yml``: UI strings from :mod:`modgen.ui_strings`,
  the cooldown tooltips and the "now" Cities rows. Polish has its own text; all
  other languages get the English text.
* ``rename_anything_chars_l_<lang>.yml``: the character table and the other
  key-to-scripted-loc indirections. These files are the same in every language
  (apart from the header) because multiplayer clients with different game
  languages must build identical names.
"""

from __future__ import annotations

from modgen.charset import CHARS, char_key
from modgen.common import EMPTY_LOC_KEY, POLISH, StateTable
from modgen.features import cities, cooldown, input_window
from modgen.ui_strings import UI

DAYS_PLACEHOLDER = "{days}"
"""Placeholder in a UI string that is replaced by the cooldown length."""

NOW_WORDS = {POLISH: "obecnie"}
"""The word "now" of the Cities rows per language; missing languages use English."""

NOW_DEFAULT = "now"
"""English "now" of the Cities rows."""

DECIMAL_DIGITS = range(10)
"""Digits that get an ``RN_DIG_<d>`` key."""


def yml_escape(text: str) -> str:
    """Return a UI string unchanged after checking it holds no double quote.

    Args:
        text: Localisation text.

    Returns:
        The same text. A lone ``"`` is also accepted unchanged.

    Raises:
        ValueError: The text contains a double quote, which would end the YAML value.
    """
    if '"' in text and text != '"':
        msg = f"double quote in UI string: {text!r}"
        raise ValueError(msg)
    return text


def ui_loc(lang: str) -> str:
    """Generate the UI strings file for one language.

    Args:
        lang: Language name; ``polish`` gets the Polish text, all others English.

    Returns:
        Contents of ``rename_anything_l_<lang>.yml`` (without BOM).
    """
    idx = 1 if lang == POLISH else 0
    days = str(cooldown.COOLDOWN_DAYS)
    o = [f"l_{lang}:\n", " # GENERATED by tools/gen.py (UI strings)\n"]
    o.extend(
        f' {k}: "{yml_escape(v[idx].replace(DAYS_PLACEHOLDER, days))}"\n' for k, v in UI.items()
    )
    o.extend(cooldown.wait_entries(lang))
    o.extend(cities.now_row_entries(NOW_WORDS.get(lang, NOW_DEFAULT)))
    return "".join(o)


def chars_loc(lang: str, states: StateTable, keys: set[int]) -> str:
    """Generate the language-independent character table for one language.

    Args:
        lang: Language name used in the ``l_<lang>:`` header.
        states: State table.
        keys: Province IDs with a vanilla VP name key.

    Returns:
        Contents of ``rename_anything_chars_l_<lang>.yml`` (without BOM).
    """
    o = [
        f"l_{lang}:\n",
        (
            " # GENERATED by tools/gen.py - language-independent tables "
            "(must be identical in every language for MP).\n"
        ),
        f' {EMPTY_LOC_KEY}: ""\n',
    ]
    o.extend(f' {char_key(c)}: "{CHARS[c]}"\n' for c in sorted(CHARS))
    o.extend(f' RN_DIG_{d}: "{d}"\n' for d in DECIMAL_DIGITS)
    o.extend(cities.chars_loc_entries(states))
    o.extend(input_window.key_label_entries())
    o.extend(cities.missing_name_entries(states, keys))
    return "".join(o)
